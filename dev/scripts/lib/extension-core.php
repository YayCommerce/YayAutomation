<?php
/**
 * The core steps, operators and data keys extension templates may use (docs/extension-api.md §12),
 * from the admin app's meta fixture. Used by `./run.sh extension-core` and by CoreStepsTest.
 *
 * @package YayMatik
 */

/**
 * Steps by id (kind, category, config and output keys), operators, data keys by item, categories.
 *
 * @param array $meta
 */
function yaymatik_extension_core( array $meta ): array {
    $automation = $meta['automation'];
    $steps      = [];
    foreach ( $automation['steps'] as $id => $step ) {
        if ( ! in_array( $step['plugin'] ?? 'yaymatik', [ 'yaymatik', 'woocommerce' ], true ) ) {
            continue;
        }
        $steps[ $id ] = [
            'kind'     => $step['kind'],
            'category' => $step['category'] ?? '',
            'config'   => array_column( $step['fields'] ?? [], 'key' ),
            'outputs'  => array_column( $step['outputs'] ?? [], 'key' ),
        ];
    }
    ksort( $steps );
    $data = [];
    foreach ( $automation['data'] as $item ) {
        $data[ $item['id'] ] = array_merge( array_column( $item['fields'], 'key' ), array_column( $item['relations'] ?? [], 'key' ) );
    }
    ksort( $data );
    return [
        'steps'      => $steps,
        'operators'  => $automation['operators'],
        'data'       => $data,
        'categories' => array_keys( $automation['categories'] ),
    ];
}

/**
 * @param array $core
 */
function yaymatik_extension_core_md( array $core ): string {
    $code  = fn( array $keys ) => $keys ? '`' . implode( '`, `', $keys ) . '`' : '—';
    $lines = [
        '# Extension API v1: core steps and data',
        '',
        'Generated by `./run.sh extension-core` from the admin app\'s meta fixture; do not edit. Public and semver\'d ([extension-api.md](extension-api.md) §12): an extension template may use these ids, config keys, output keys, operators and data keys.',
        '',
        '## Steps',
        '',
        '| Id | Kind | Category | Config keys | Output keys |',
        '|---|---|---|---|---|',
    ];
    foreach ( $core['steps'] as $id => $step ) {
        $lines[] = "| `{$id}` | {$step['kind']} | " . ( '' === $step['category'] ? '—' : "`{$step['category']}`" ) . ' | ' . $code( $step['config'] ) . ' | ' . $code( $step['outputs'] ) . ' |';
    }
    array_push( $lines, '', '## Condition operators', '', '| Field type | Operators |', '|---|---|' );
    foreach ( $core['operators'] as $type => $operators ) {
        $lines[] = "| `{$type}` | " . $code( $operators ) . ' |';
    }
    array_push( $lines, '', '## Data items', '', '| Item | Fields and relations |', '|---|---|' );
    foreach ( $core['data'] as $item => $keys ) {
        $lines[] = "| `{$item}` | " . $code( $keys ) . ' |';
    }
    array_push( $lines, '', '## Categories', '', $code( $core['categories'] ), '' );
    return implode( "\n", $lines );
}
