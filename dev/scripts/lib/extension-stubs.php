<?php
/**
 * PHPStan stubs of the public Extension API (includes/Api): signatures and docblocks, no bodies.
 *
 * @package YayMatik
 */

/**
 * The stubs file's content.
 *
 * @param string $api_dir
 */
function yaymatik_extension_stubs( string $api_dir ): string {
    $files = glob( $api_dir . '/*.php' );
    sort( $files );
    $classes = [];
    foreach ( $files as $file ) {
        require_once $file;
        $classes[] = yaymatik_extension_stubs_class( new ReflectionClass( 'YayMatik\\Api\\' . basename( $file, '.php' ) ) );
    }
    return "<?php\n/**\n * YayMatik Extension API " . YayMatik\Api\Api::VERSION . ": PHPStan stubs (docs/extension-api.md, Check your extension).\n"
        . " * Generated by `./run.sh extension-stubs` in YayMatik; don't edit.\n */\n\nnamespace YayMatik\\Api;\n\n"
        . implode( "\n", $classes );
}

/**
 * Public constants and methods; a private constructor as one without parameters, so `new` stays an error.
 *
 * @param ReflectionClass $class_ref
 */
function yaymatik_extension_stubs_class( ReflectionClass $class_ref ): string {
    if ( $class_ref->getParentClass() || $class_ref->getInterfaceNames() ) {
        throw new LogicException( esc_html( $class_ref->getName() . ': the stubs don\'t write extends / implements yet.' ) );
    }
    $members = [];
    foreach ( $class_ref->getReflectionConstants() as $constant ) {
        if ( $constant->isPublic() ) {
            $members[] = yaymatik_extension_stubs_doc( $constant->getDocComment() ) . '    public const ' . $constant->getName() . ' = ' . yaymatik_extension_stubs_value( $constant->getValue() ) . ';';
        }
    }
    foreach ( $class_ref->getMethods() as $method ) {
        if ( $method->isPrivate() && $method->isConstructor() ) {
            $members[] = '    private function __construct() {}';
        } elseif ( $method->isPublic() ) {
            $params    = implode( ', ', array_map( 'yaymatik_extension_stubs_param', $method->getParameters() ) );
            $members[] = yaymatik_extension_stubs_doc( $method->getDocComment() ) . '    public ' . ( $method->isStatic() ? 'static ' : '' ) . 'function ' . $method->getName()
                . ( '' === $params ? '()' : "( {$params} )" )
                . ( $method->hasReturnType() ? ': ' . yaymatik_extension_stubs_type( $method->getReturnType() ) : '' )
                . ( $class_ref->isInterface() ? ';' : ' {}' );
        }
    }
    $kind = $class_ref->isInterface() ? 'interface' : ( $class_ref->isFinal() ? 'final class' : 'class' );
    return ( $class_ref->getDocComment() ? $class_ref->getDocComment() . "\n" : '' ) . "{$kind} {$class_ref->getShortName()} {\n\n" . implode( "\n\n", $members ) . "\n}\n";
}

/**
 * @param string|false $doc
 */
function yaymatik_extension_stubs_doc( $doc ): string {
    return $doc ? "    {$doc}\n" : '';
}

/**
 * @param ReflectionParameter $param
 */
function yaymatik_extension_stubs_param( ReflectionParameter $param ): string {
    return ( $param->hasType() ? yaymatik_extension_stubs_type( $param->getType() ) . ' ' : '' )
        . ( $param->isVariadic() ? '...' : '' ) . '$' . $param->getName()
        . ( $param->isDefaultValueAvailable() ? ' = ' . yaymatik_extension_stubs_value( $param->getDefaultValue() ) : '' );
}

/**
 * Class names fully qualified: the stubs live in another project.
 *
 * @param ReflectionNamedType $type
 */
function yaymatik_extension_stubs_type( ReflectionNamedType $type ): string {
    $name = $type->isBuiltin() || 'self' === $type->getName() ? $type->getName() : '\\' . $type->getName();
    return ( $type->allowsNull() && 'mixed' !== $name ? '?' : '' ) . $name;
}

/**
 * @param mixed $value
 */
function yaymatik_extension_stubs_value( $value ): string {
    if ( [] === $value ) {
        return '[]';
    }
    return null === $value ? 'null' : var_export( $value, true ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export
}
