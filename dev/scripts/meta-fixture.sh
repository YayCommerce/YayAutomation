#!/bin/bash
# Write the admin app's test fixture: window.yayMatikMeta from the local site (wp-cli).
cd "$(dirname "$0")/../.." || exit 1
[[ -f yaymatik.php ]] || { echo "Not the plugin root: $(pwd)"; exit 1; }
command -v wp >/dev/null || { echo "Missing: wp-cli"; exit 1; }

out=apps/admin-page/src/test/fixtures/meta.json
mkdir -p "$(dirname "$out")"

# English labels; site-specific and per-request values replaced. WooCommerce option lists (statuses,
# payment methods) still come from the site that ran it, so regenerate from a plain WooCommerce install.
wp ${WP_PATH:+--path="$WP_PATH"} eval '
switch_to_locale( "en_US" );
// The sender is read by SendInternalEmail (field text and automation.email): never the dev site sender.
add_filter( "pre_option_woocommerce_email_from_name", fn() => "Example Store" );
add_filter( "pre_option_woocommerce_email_from_address", fn() => "store@example.test" );
// Also the Send internal email "To" placeholder.
add_filter( "pre_option_admin_email", fn() => "admin@example.test" );
$meta = \YayMatik\Engine\BEPages\AdminPage::client_meta();
$meta["plugin"]["version"]      = "0.0.0";
$meta["wc"]["currencySymbol"]   = "$";
$meta["wc"]["cartTracking"]     = false;
$meta["wc"]["abandonMinutes"]   = 60;
$meta["wc"]["reviewsEnabled"]   = true;
$meta["plugin"]["pluginUrl"]  = "https://example.test/wp-content/plugins/yaymatik/";
$meta["wp"]["restRoot"]       = "https://example.test/wp-json/";
$meta["wp"]["restNonce"]      = "test-nonce";
$meta["wp"]["siteUrl"]        = "https://example.test";
$meta["wp"]["adminUrl"]       = "https://example.test/wp-admin/";
$meta["wp"]["adminEmail"]     = "admin@example.test";
$meta["wp"]["userEmail"]      = "you@example.test";
$meta["wp"]["timezoneString"] = "UTC";
$meta["wp"]["gmtOffset"]      = 0;
// JSON has no comments: this first key is the header.
$meta = [ "//" => "Generated by ./run.sh meta-fixture from AdminPage::client_meta() (the catalog is Workflow\\Core\\Definition\\Catalog). Catalog change → ./run.sh meta-fixture; never edit by hand." ] + $meta;
echo wp_json_encode( $meta, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE ), "\n";
' > "$out.tmp" && mv "$out.tmp" "$out" || { rm -f "$out.tmp"; echo "wp eval failed"; exit 1; }

echo "Wrote $out"
